"""
Unit Tests for BrightPath Flask Backend & Local AI Agent
Tests:
  - Flask endpoints (health, children, sessions, progress, diagnostics, agent)
  - Scikit-learn performance and trajectory slope analysis on real session data
  - Agent coordination and educational game recommendations
  - Ethical reporting on historical diagnostic categories
Zero external APIs. Zero FastAPI dependencies.
"""

import unittest
from backend.app.main import app

class TestBrightPathFlaskBackend(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        app.testing = True
        cls.client = app.test_client()

    def test_01_health_check(self):
        res = self.client.get("/api/health")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data.get("status"), "healthy")
        self.assertEqual(data.get("framework"), "Flask")
        self.assertEqual(data.get("ml_framework"), "scikit-learn")
        self.assertFalse(data.get("external_api_used"))

    def test_02_agent_status(self):
        res = self.client.get("/api/agent/status")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data.get("status"), "active")
        meta = data.get("agent_metadata", {})
        self.assertIn("BrightPath", meta.get("name"))
        self.assertFalse(meta.get("external_apis_used"))

    def test_03_diagnostic_model_info(self):
        res = self.client.get("/api/diagnostics/model-info")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertFalse(data.get("model_available"))
        self.assertEqual(data.get("honest_message"), "Diagnostic prediction model not available")
        self.assertIn("categories", data)
        cat_names = [c["name"] for c in data["categories"]]
        self.assertIn("Autistic Disorder", cat_names)
        self.assertIn("Asperger Syndrome", cat_names)
        self.assertIn("Childhood Disintegrative Disorder", cat_names)
        self.assertTrue(any("PDD-NOS" in name for name in cat_names))

    def test_04_create_child_profile(self):
        payload = {
            "childId": "child_test_agent_01",
            "name": "Maya Explorer",
            "age": 5,
            "mode": "early",
            "notes": "Prefers sensory-calm activities"
        }
        res = self.client.post("/api/children", json=payload)
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data.get("name"), "Maya Explorer")
        self.assertEqual(data.get("mode"), "early")

    def test_05_agent_session_processing(self):
        session_payload = {
            "id": "session_flask_test_001",
            "childId": "child_test_agent_01",
            "childName": "Maya Explorer",
            "childAge": 5,
            "activityMode": "early",
            "activityId": "bubble-pop",
            "activityName": "Bubble Pop",
            "score": 92,
            "accuracy": 90,
            "responseTime": 1.4,
            "duration": 60,
            "initialEmotion": "Neutral",
            "finalEmotion": "Happy",
            "motorMetrics": {
                "tapAccuracy": 94,
                "avgResponseTime": 1.4,
                "completionTime": 60
            },
            "repetitiveMetrics": {
                "repetitionFrequency": 0.5,
                "rhythmConsistency": 90
            }
        }
        res = self.client.post("/api/sessions", json=session_payload)
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        
        # Verify Agent Analysis attachment
        self.assertIn("agentAnalysis", data)
        agent_out = data["agentAnalysis"]
        
        # Verify scikit-learn performance analytics
        perf = agent_out.get("performance_analysis", {})
        self.assertEqual(perf.get("performance_tier"), "High Focus & Mastery")
        self.assertEqual(perf.get("score"), 92.0)
        
        # Verify trajectory trends on real session
        trends = agent_out.get("trajectory_trends", {})
        self.assertIn("total_sessions_analyzed", trends)
        
        # Verify adaptive recommendation generated by agent
        rec = agent_out.get("next_recommendation", {})
        self.assertTrue(rec.get("name"))
        self.assertIn("agent_rationale", rec)

        # Verify historical diagnostic categories limitation
        diag = data.get("diagnosticResults", {})
        self.assertFalse(diag.get("model_available"))
        self.assertEqual(diag.get("honest_message"), "Diagnostic prediction model not available")
        categories = diag.get("categories", [])
        self.assertEqual(len(categories), 4)
        for cat in categories:
            self.assertIsNone(cat.get("prediction_percentage"))

    def test_06_on_demand_recommendation(self):
        payload = {
            "emotion": "Frustrated",
            "age": 10,
            "mode": "brightpath"
        }
        res = self.client.post("/api/agent/recommend", json=payload)
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data.get("name"), "Step-by-Step Puzzle")
        self.assertIn("agent_rationale", data)

    def test_07_get_child_progress(self):
        res = self.client.get("/api/progress/child_test_agent_01")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data.get("childId"), "child_test_agent_01")
        self.assertTrue(data.get("totalSessions") >= 1)

    def test_08_evaluate_diagnostics(self):
        res = self.client.post("/api/diagnostics/evaluate", json={"score": 85, "accuracy": 90})
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertFalse(data.get("model_available"))
        self.assertEqual(len(data.get("categories", [])), 4)

    def test_09_session_diagnostics(self):
        res = self.client.get("/api/diagnostics/session/session_flask_test_001")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertFalse(data.get("model_available"))

    def test_10_analyze_session(self):
        res = self.client.post("/api/sessions/session_flask_test_001/analyze")
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertIn("agentAnalysis", data)

if __name__ == "__main__":
    unittest.main()

